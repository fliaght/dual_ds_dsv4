#!/usr/bin/env bash
# TensorFold adapter (jayleaton/deepseek-v41-tensorfold-spark, Python path): our UMA precheck and
# memory guards around its scripts/serve.sh. Evaluation only; the vLLM service stays the default.
#
#   bash scripts/tf-service.sh setup | start | stop | status
#
# TF_DIR is the pinned recipe checkout with our patches (config/tensorfold) and its git-ignored
# config/prod.env, which `setup` generates from cluster.conf (Docs/runbooks/tensorfold.md).
# Never run it beside the vLLM service: same GPUs, port 8000.
set -euo pipefail
source "$(dirname "$0")/_lib.sh"
: "${V41_PACKED_DIR:?TensorFold reads packed Engram: set V41_PACKED_DIR in cluster.conf (v41-service.sh pack)}"
TF_DIR="${TF_DIR:-$HOME/tf/deepseek-v41-tensorfold-spark}"
TF_STATE="${TF_STATE:-$HOME/tf-state}"
TF_RECIPE_URL=https://github.com/jayleaton/deepseek-v41-tensorfold-spark.git
TF_RECIPE_COMMIT=2dcce0303451da2a59f80e6c7413da8b3b0f7a57
TF_IMAGE="${TF_IMAGE:-dsv41-tensorfold:060-g19-2dcce03}"
TF_CONF="$ROOT_DIR/config/tensorfold"
TF_NAME=dsv41-tf
GUARD_UNIT=dsv41-tf-guard
ACTION="${1:-status}"

serve() { (cd "$TF_DIR" && scripts/serve.sh "$@"); }

precheck() {  # same UMA rule as the vLLM path (v41-service.sh local-precheck)
  for_each_node "set -e
    a=\$(awk '/^MemAvailable:/{print int(\$2/1024)}' /proc/meminfo); f=\$(awk '/^MemFree:/{print int(\$2/1024)}' /proc/meminfo)
    echo \"MemAvailable=\$a MemFree=\$f\"
    [ \$a -ge 119208 ] && [ \$f -ge 111016 ] || { echo 'Insufficient UMA headroom' >&2; exit 1; }
    [ -z \"\$(nvidia-smi --query-compute-apps=pid --format=csv,noheader)\" ] || { echo 'GPU busy' >&2; exit 1; }
    [ -z \"\$(docker ps -q --filter name=vllm-dsv41)\" ] || { echo 'vLLM container running' >&2; exit 1; }"
}

guard_cmd() {  # $1 = rank, $2 = repo root on that node, $3 = peer address
  local me="$TF_NAME-r$1" other="$TF_NAME-r$((1 - $1))"
  echo "systemctl --user stop $GUARD_UNIT 2>/dev/null; systemd-run --user --unit=$GUARD_UNIT --collect \
-p MemoryMax=128M -p MemorySwapMax=0 -p 'ExecStopPost=-/usr/bin/docker kill $me' \
-p 'StandardOutput=append:$LOG_DIR/tf-guard.log' -p 'StandardError=append:$LOG_DIR/tf-guard.log' \
/usr/bin/python3 $2/scripts/memory_guard.py --container $me --reserve-mib $WATCHDOG_THRESHOLD_MIB \
--state $LOG_DIR/tf-guard.json --peer $3 --peer-container $other \
--cache-dir $V41_MODEL_DIR --cache-dir $V41_PACKED_DIR \
--reclaim-cgroup /sys/fs/cgroup/user.slice/user-\$(id -u).slice/user@\$(id -u).service"
}

active_hcas() {  # $1 = node: its RoCE devices with port 1 ACTIVE, comma-separated
  ssh_node "$1" 'for d in /sys/class/infiniband/*; do
    [ "$(cat $d/ports/1/state 2>/dev/null)" = "4: ACTIVE" ] && printf "%s," "${d##*/}"; done; true' | sed 's/,$//'
}

write_env() {  # recipe example minus unset.keys, then cluster.conf values, then site.env
  local keys head_hca worker_hca
  keys=$(sed -E 's/#.*//; s/[[:space:]]+//g; /^$/d' "$TF_CONF/unset.keys" | paste -sd'|')
  head_hca=$(active_hcas "$LEADER"); worker_hca=$(active_hcas "${NODE_ARR[1]}")
  [ -n "$head_hca" ] && [ -n "$worker_hca" ] || { echo 'no ACTIVE RoCE port on a node' >&2; return 1; }
  sed -E "s/^(($keys)=)/# [dual_ds_dsv4] removed: \1/" "$TF_DIR/config/prod.env.example"
  printf '\n# ===== dual_ds_dsv4: generated by scripts/tf-service.sh setup from cluster.conf; edit there =====\n'
  local kv
  for kv in "WORKER_SSH=$(id -un)@${NODE_ARR[1]}" "HEAD_IP=$LEADER" "NCCL_SOCKET_IFNAME=${IFACES%% *}" \
      "HEAD_IB_HCA=$head_hca" "WORKER_IB_HCA=$worker_hca" "NCCL_IB_GID_INDEX=${NCCL_IB_GID_INDEX:-0}" \
      "IMAGE=$TF_IMAGE" "CACHE_VOL=$TF_STATE/cache" "HEAD_MODEL=$V41_MODEL_DIR" "WORKER_MODEL=$V41_MODEL_DIR" \
      "HEAD_ENGRAM=$V41_PACKED_DIR" "WORKER_ENGRAM=$V41_PACKED_DIR" "HEAD_PREPARED=$TF_STATE/prepared" \
      "WORKER_PREPARED=$TF_STATE/prepared" "HEAD_STATE=$TF_STATE/state" "WORKER_STATE=$TF_STATE/state" \
      "STATE_DIR=$TF_STATE/ops" "NAME=$TF_NAME" "PORT=$API_PORT" "SERVED_NAME=$MODEL"; do
    printf '%s=%q\n' "${kv%%=*}" "${kv#*=}"
  done
  printf '\n# ===== dual_ds_dsv4: config/tensorfold/site.env =====\n'
  cat "$TF_CONF/site.env"
}

setup() {  # pinned checkout + our patches + generated prod.env; never overwrites an existing prod.env
  [ -d "$TF_DIR/.git" ] || git clone -q "$TF_RECIPE_URL" "$TF_DIR"
  local head; head=$(git -C "$TF_DIR" rev-parse HEAD)
  if [ "$head" != "$TF_RECIPE_COMMIT" ]; then
    git -C "$TF_DIR" diff --quiet || { echo "$TF_DIR has local changes at $head; expected $TF_RECIPE_COMMIT" >&2; exit 1; }
    git -C "$TF_DIR" checkout -q "$TF_RECIPE_COMMIT"
  fi
  git -C "$TF_DIR" submodule update --init -q
  git -C "$TF_DIR" apply --reverse --check "$TF_CONF/recipe.patch" 2>/dev/null \
    || git -C "$TF_DIR" apply "$TF_CONF/recipe.patch"
  cp "$TF_CONF/0003-roce-nic-pairing.patch" "$TF_DIR/patches/"
  mkdir -p "$TF_STATE"/{cache,prepared,state,ops}
  local env="$TF_DIR/config/prod.env"
  write_env > "$env.new"
  if [ ! -f "$env" ]; then mv "$env.new" "$env"; echo "wrote $env"
  elif cmp -s "$env" "$env.new"; then rm "$env.new"; echo "$env is current"
  else echo "$env differs; review then move into place:"; diff -u "$env" "$env.new" | tail -n +3 || true; fi
}

stop_all() {
  serve stop || true
  for_each_node "systemctl --user stop $GUARD_UNIT 2>/dev/null || true; docker rm -f $TF_NAME-r0 $TF_NAME-r1 >/dev/null 2>&1 || true"
}

case "$ACTION" in
  setup)
    setup ;;
  start)
    precheck
    worker="${NODE_ARR[1]}"
    ssh_node "$worker" "mkdir -p '$REMOTE_STAGE/scripts'"
    scp -q "$ROOT_DIR/scripts/memory_guard.py" "$worker:$REMOTE_STAGE/scripts/"
    bash -c "$(guard_cmd 0 "$ROOT_DIR" "$worker")"
    ssh_node "$worker" "$(guard_cmd 1 "$REMOTE_STAGE" "$LEADER")"
    for_each_node "systemctl --user is-active $GUARD_UNIT"
    if ! { serve preflight && serve start; }; then
      echo 'TensorFold start failed; stopping both ranks and guards' >&2
      stop_all; exit 1
    fi
    for_each_node "systemctl --user is-active $GUARD_UNIT" ;;
  stop)
    stop_all
    for_each_node "docker ps -a --filter name=$TF_NAME --format '{{.Names}} {{.Status}}'" ;;
  status)
    serve status || true
    for_each_node "systemctl --user show $GUARD_UNIT -p ActiveState --value; cat $LOG_DIR/tf-guard.json 2>/dev/null | cut -c1-200" ;;
  *)
    echo "usage: $0 setup|start|stop|status" >&2; exit 2 ;;
esac
